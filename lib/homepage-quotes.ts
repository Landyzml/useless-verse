export function randomQuoteIndex(total:number, previous:number|null, random=Math.random):number {
 if(total<=1)return 0;
 const valid=previous!==null&&Number.isInteger(previous)&&previous>=0&&previous<total;
 const n=Math.floor(random()*(valid?total-1:total));
 return valid&&n>=previous! ? n+1 : n;
}
